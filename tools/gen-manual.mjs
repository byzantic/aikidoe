const typeText = (s, root) => {
  if (!s || s === true) return 'any';
  if (s.$ref) return `[${s.$ref.split('/').pop()}](#${s.$ref.split('/').pop().toLowerCase()})`;
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``;
  if (s.enum) return s.enum.map(v => `\`${JSON.stringify(v)}\``).join(' \\| ');
  if (s.anyOf || s.oneOf) return (s.anyOf ?? s.oneOf).map(x => typeText(x, root)).join(' or ');
  const t = [].concat(s.type ?? []).join(' or ');
  if (s.type === 'array') return `list of ${typeText(s.items === undefined ? true : s.items, root)}${s.minItems ? ` (at least ${s.minItems})` : ''}`;
  const lim = [s.minimum !== undefined ? `≥ ${s.minimum}` : '', s.exclusiveMinimum !== undefined ? `> ${s.exclusiveMinimum}` : '', s.maximum !== undefined ? `≤ ${s.maximum}` : '', s.pattern ? `matching \`${s.pattern}\`` : ''].filter(Boolean).join(', ');
  return `${t || 'object'}${lim ? ` (${lim})` : ''}`;
};

export function referenceStudyFormat() {
  const s = JSON.parse(readFileSync(join(ROOT, 'schema', 'study.schema.json'), 'utf8'));
  const table = (obj) => {
    const req = new Set(obj.required ?? []);
    return ['| field | type | |', '|---|---|---|', ...Object.entries(obj.properties ?? {}).map(([k, v]) => `| \`${k}\`${req.has(k) ? ' (required)' : ''} | ${typeText(v, s)} | ${(v.description ?? '').replace(/\|/g, '\\|')} |`)].join('\n');
  };
  const defs = Object.entries(s.$defs).filter(([, d]) => d.properties);
  return `${GENERATED}

# Study file format

A study is one JSON file, \`NAME.aikidoe.json\`: the factors and responses, the design with its
run order, every observation, the measurement structure and the history of stages. It is the
record of the experiment; the app and \`doe\` read and write the same file. Comments (\`//\`,
\`/* */\`) and trailing commas are allowed.

${s.description}

The format is published as a JSON Schema: [schema/study.schema.json](../../schema/study.schema.json)
(\`doe schema\` prints it). The schema checks the structure;
the library checks the rest when it reads a study:

> ${s.$comment}

## Top level

${table(s)}

## factor

A factor is [continuous](#continuous) or [categorical](#categorical).

## id

${s.$defs.id.description} (\`${s.$defs.id.pattern}\`).

## label

${s.$defs.label.description}.

${defs.map(([k, d]) => `## ${k}\n\n${d.description ? `${d.description}\n\n` : ''}${table(d)}${d.anyOf && k === 'continuous' ? '\n\nGive `low` and `high`, or `levels` (then the range is their extent).' : ''}${k === 'categorical' ? '\n\nWithout `type`, a factor whose levels include a string is categorical.' : ''}`).join('\n\n')}

## constraint

${s.$defs.constraint.description}: a string, or \`{ "expr": …, "units": "natural" | "coded" }\`.

## A minimal study

\`\`\`json
{
  "aikidoe": 1,
  "name": "Etch rate",
  "seed": 12345,
  "factors": [
    { "id": "power", "low": 200, "high": 400, "units": "W" },
    { "id": "gas", "levels": ["CF4", "C2F6"] }
  ],
  "responses": [{ "id": "rate", "units": "nm/min" }]
}
\`\`\`
`;
}

// ---------------------------------------------------------------- console blocks

/** The console blocks and file blocks of a page, in order. */
export function blocksOf(md) {
  return parse(md).filter(b => b.type === 'code' && (b.lang === 'console' || b.lang === 'file'));
}

const normalise = (s) => s.replace(/\bin \d+(\.\d+)? s\b/g, 'in … s').split('\n').map(l => l.replace(/\s+$/, '')).join('\n').replace(/\n+$/, '');

/** Does the actual output match the expected text (a line "…" skips any number of lines)? */
export function outputMatches(expected, actual) {
  const E = normalise(expected).split('\n'), A = normalise(actual).split('\n');
  const go = (i, j) => {
    if (i === E.length) return j === A.length;
    if (E[i].trim() === '…') { for (let k = j; k <= A.length; k++) if (go(i + 1, k)) return true; return false; }
    return j < A.length && E[i] === A[j] && go(i + 1, j + 1);
  };
  if (E.length === 1 && E[0] === '' && (A.length === 1 && A[0] === '')) return true;
  return go(0, 0);
}

/**
 * Run a page's blocks in a fresh directory (with examples/ copied in). Returns
 * [{ block, commands: [{ cmd, expected, actual, code }] }].
 */
export function runPage(md) {
  const dir = mkdtempSync(join(tmpdir(), 'aikidoe-manual-'));
  cpSync(join(ROOT, 'examples'), join(dir, 'examples'), { recursive: true });
  const results = [];
  try {
    for (const b of blocksOf(md)) {
      if (b.lang === 'file') { writeFileSync(join(dir, b.info), b.text.endsWith('\n') ? b.text : b.text + '\n'); continue; }
      const cmds = [];
      let cur = null;
      for (const line of b.text.split('\n')) {
        if (line.startsWith('$ ')) { cur = { cmd: line.slice(2), expected: [] }; cmds.push(cur); } else if (cur) cur.expected.push(line);
      }
      for (const c of cmds) {
        const args = shellWords(c.cmd);
        if (args[0] !== 'doe') throw new Error(`manual console blocks run doe only: "${c.cmd}"`);
        const r = spawnSync(process.execPath, [DOE, ...args.slice(1)], { cwd: dir, encoding: 'utf8' });
        c.expected = c.expected.join('\n'); c.actual = (r.stdout + (r.stderr ? r.stderr : '')).replace(/\n$/, ''); c.code = r.status;
      }
      results.push({ block: b, commands: cmds });
    }
  } finally { rmSync(dir, { recursive: true, force: true }); }
  return results;
}

/** Split a command line like a shell would for simple quoting ("…", '…'). */
export function shellWords(s) {
  const out = []; let cur = '', q = null, any = false;
  for (const ch of s) {
    if (q) { if (ch === q) q = null; else cur += ch; continue; }
    if (ch === '"' || ch === "'") { q = ch; any = true; continue; }
    if (/\s/.test(ch)) { if (cur || any) out.push(cur); cur = ''; any = false; continue; }
    cur += ch;
  }
  if (cur || any) out.push(cur);
  return out;
}

/** Rewrite a page with the actual outputs of its console blocks (keeping "…" elisions out). */
export function withOutputs(md) {
  const res = runPage(md);
  let out = md;
  for (const { block, commands } of res) {
    const text = commands.map(c => `$ ${c.cmd}\n${c.actual}`.replace(/\n$/, '')).join('\n');
    out = out.replace('```console\n' + block.text + '\n```', '```console\n' + text + '\n```');
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(MANUAL, 'reference-cli.md'), referenceCli());
  writeFileSync(join(MANUAL, 'reference-study-format.md'), referenceStudyFormat());
  console.log('wrote reference-cli.md and reference-study-format.md');
  if (process.argv.includes('--outputs')) {
    const only = process.argv.slice(2).filter(a => !a.startsWith('--'));
    for (const f of readdirSync(MANUAL).filter(f => f.endsWith('.md') && (!only.length || only.includes(f.replace(/\.md$/, ''))))) {
      const md = readFileSync(join(MANUAL, f), 'utf8');
      if (!blocksOf(md).some(b => b.lang === 'console')) continue;
      const next = withOutputs(md);
      if (next !== md) { writeFileSync(join(MANUAL, f), next); console.log(`updated outputs in ${f}`); }
    }
  }
}
