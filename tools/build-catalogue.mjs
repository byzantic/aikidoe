// Build js/design/catalogue.js: minimum-aberration 2^(k−p) designs for N = 8 … 128 runs and
// k ≤ 15 factors, found by searchMinAberration (js/design/twolevel.js). The result is checked
// against FrF2's catalogue in tests/design.test.mjs (word-length patterns must agree).
//
//   node tools/build-catalogue.mjs [--check]     --check: verify the committed file is reproduced
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { searchMinAberration, maskToWord, regularDesign, resolution } from '../js/design/twolevel.js';

const out = fileURLToPath(new URL('../js/design/catalogue.js', import.meta.url));
const entries = [];
for (let q = 3; q <= 7; q++) for (let k = q + 1; k <= Math.min(15, (1 << q) - 1); k++) {
  const t = Date.now();
  const r = searchMinAberration(q, k, { seed: 1 });
  const d = regularDesign(q, r.gens);
  entries.push([`${k}-${k - q}`, { runs: 1 << q, gens: r.gens.map(maskToWord), resolution: resolution(d), wlp: r.wlp }]);
  process.stderr.write(`${k}-${k - q} (${1 << q} runs): ${Date.now() - t} ms\n`);
}
const body = `// Minimum-aberration regular two-level designs, keyed "k-p": ${entries.length} designs, N = 8 … 128
// runs, k ≤ 15 factors. GENERATED by tools/build-catalogue.mjs (searchMinAberration, seed 1) —
// do not edit. Generators are products of the q = log2(N) base factors A, B, C, … for the added
// factors in order. wlp[L−1] = number of defining words of length L. Checked against FrF2's
// catalogue (Chen, Sun & Wu 1993; Block & Mee 2005) by tests/design.test.mjs.
export const CATALOGUE = {
${entries.map(([key, e]) => `  '${key}': { runs: ${e.runs}, gens: ${JSON.stringify(e.gens)}, resolution: ${e.resolution}, wlp: ${JSON.stringify(e.wlp)} },`).join('\n')}
};
`;
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== body) { console.error('js/design/catalogue.js is not reproduced by the search'); process.exit(1); }
  console.log('catalogue reproduced');
} else { writeFileSync(out, body); console.log(`wrote ${out}`); }
