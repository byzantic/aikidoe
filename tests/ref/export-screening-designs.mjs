// Writes tests/ref/fixture.screening-designs.json: aikidoe's screening designs (coded matrices),
// the input of projectivity_r.R (issue #79), which measures them independently. Re-run when a
// design generator changes: node tests/ref/export-screening-designs.mjs
import { writeFileSync } from 'node:fs';
import { pbMatrix } from '../../js/design/pb.js';
import { definitiveScreening } from '../../js/design/dsd.js';
import { fractionalFactorial } from '../../js/design/factorial.js';

const designs = [];
for (const N of [12, 16, 20, 24, 28, 32, 36, 40, 44, 48]) designs.push({ name: `pb${N}`, kind: 'pb', X: pbMatrix(N) });
designs.push({ name: 'pb40-38cols', kind: 'pb', X: pbMatrix(40).map(r => r.slice(0, 38)) });
for (const [k, runs] of [[7, 16], [9, 16], [5, 16], [6, 8]]) designs.push({ name: `frac-${k}-${k - Math.log2(runs)}`, kind: 'fraction', X: fractionalFactorial(k, { runs }).X });
for (const [k, fake, cats] of [[4, 0, []], [4, 2, []], [5, 0, []], [6, 0, []], [8, 0, []], [8, 0, [6, 7]], [10, 0, []], [12, 0, []], [14, 0, []]]) {
  designs.push({ name: `dsd-${k}${fake ? `-fake${fake}` : ''}${cats.length ? `-cat${cats.length}` : ''}`, kind: 'dsd', X: definitiveScreening(k, { fake, categorical: cats }).X, categorical: cats });
}
writeFileSync(new URL('./fixture.screening-designs.json', import.meta.url), JSON.stringify({ note: 'generated by tests/ref/export-screening-designs.mjs from aikidoe\'s generators', designs }) + '\n');
console.log(`wrote ${designs.length} designs`);
